# ── 所有「要求模型输出 JSON」的角色共用这一段 ──
# 加它的直接原因：模型解释正文时爱用英文双引号去引原句（把"塞回遮阳板"改成…），
# 未转义的引号会让 JSON 在那个位置提前结束，报 Expecting ',' delimiter，
# 整份输出直接作废、整章白写。改成中文引号即可根治。
JSON_ESCAPE_RULE = """

【JSON 转义铁律 —— 违反会使整份输出作废，必须严格遵守】
1. 字符串值内部绝对不要出现英文双引号 "，需要引用原文一律用中文引号「」。
   正确： "suggestion": "删除「塞回遮阳板」这半句，只保留「塞进背包的夹层」。"
   错误： "suggestion": "删除"塞回遮阳板"这半句。"
2. 字符串值内部不要出现真实换行，需要分段时写成 \\n。
3. 数字与 true / false 不要加引号。
4. 不要在 JSON 前后输出任何解释、寒暄或 ``` 代码块标记。"""

# 校对输出最容易超长（要摘原文、写问题和建议），单列一段篇幅上限。
# 拆分后每个 specialist 只管一个维度，这 5 条额度就都花在自己那一维上，
# 不会再出现"四个维度抢 5 条额度、只报得出最显眼的一个"的情况。
REVIEW_LIMITS = """

【篇幅硬性上限 —— 超了会导致 JSON 被截断而作废】
- comments 最多 5 条，按严重程度排序，只保留最关键的问题。
- quote 摘录不超过 30 字，且必须用「」包裹。
- issue、suggestion 各不超过 60 字，直接说结论，不要复述原文。
- 整份 JSON 控制在 800 字以内。"""


